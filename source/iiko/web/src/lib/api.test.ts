import { pickOrg, type Branch } from './api'

/* Регрессия: по ссылке филиала сайт показывал ДЕМО-ДАННЫЕ.

   Филиал сохраняется в localStorage, чтобы F5 не уводил владельца на первый по
   алфавиту. Но сохранённый выбор переживал и смену ссылки: человек однажды
   смотрел демо, открывал ссылку своего филиала — и экраны продолжали
   спрашивать demo-org-1, который бэкенд пропускает даже по ссылке филиала.
   Сохранённый филиал действителен, только если он есть среди доступных. */

const b = (id: string): Branch => ({ organization_id: id, organization_name: id })

describe('какой филиал показывать', () => {
  it('чужой сохранённый филиал не переживает ссылку — берём из ссылки', () => {
    expect(pickOrg([b('alieva')], 'demo-org-1')).toBe('alieva')
  })
  it('филиал не выбран — берём первый доступный', () => {
    expect(pickOrg([b('alieva')], '')).toBe('alieva')
  })
  it('свой сохранённый филиал остаётся: F5 не уводит владельца на первый по алфавиту', () => {
    expect(pickOrg([b('beibitshilik'), b('alieva')], 'alieva')).toBe('alieva')
  })
  it('список не приехал — ничего не трогаем, чтобы не сбить выбор', () => {
    expect(pickOrg([], 'alieva')).toBe('alieva')
  })
})
