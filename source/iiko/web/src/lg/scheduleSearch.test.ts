import { norm } from './Schedule'

/* Имена сотрудников приезжают из iiko, где латиница и кириллица перемешаны
   прямо внутри одного справочника. Управляющий ищет свою букву и не находит
   человека, хотя тот в списке есть. */
describe('поиск сотрудника не спотыкается о раскладку', () => {
  it('кириллическая «а» находит латинскую', () => {
    expect(norm('Алия').includes(norm('a'))).toBe(true)
  })
  it('латинская «a» находит кириллическую', () => {
    expect(norm('Канат').includes(norm('а'))).toBe(true)
  })
  it('имя со смешанными буквами ищется целиком', () => {
    // «Sholpan» с кириллической «о» внутри — обычное дело в реальных справочниках
    expect(norm('Shоlpan')).toBe(norm('Sholpan'))
  })
  it('регистр и пробелы по краям не мешают', () => {
    expect(norm('  ЖАНАРЫС ')).toBe(norm('Жанарыс'))
  })
  it('разные люди не склеиваются', () => {
    expect(norm('Assel').includes(norm('Daulet'))).toBe(false)
  })
})
