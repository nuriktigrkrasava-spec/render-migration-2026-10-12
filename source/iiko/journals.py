# ── Чистые функции ──────────────────────────────────────────────────────────

def _hm(s: str) -> int:
    """'15:00' → минуты от полуночи. Для сравнения слотов со временем."""
    h, m = s.split(":")
    return int(h) * 60 + int(m)


def slot_is_due(slot: str, now: datetime) -> bool:
    """Наступил ли срок слота. Слот 23:45 «горит» только в тот же день."""
    return now.hour * 60 + now.minute >= _hm(slot)


def due_items(now: datetime) -> List[Tuple[str, str, str]]:
    """Что положено сдать к этому времени: [(kind, zone_or_'', slot)].

    Именно от этого списка считается «сдано N из M» — иначе филиал выглядел бы
    должником в 11 утра за вечерний слот, до которого ещё восемь часов.
    """
    out: List[Tuple[str, str, str]] = []
    for slot in CLEAN_SLOTS:
        if slot_is_due(slot, now):
            for z in ZONE_ORDER:
                out.append(("clean", z, slot))
    for slot in TEMP_SLOTS:
        if slot_is_due(slot, now):
            out.append(("temp", "", slot))
    if slot_is_due(STOCK_SLOT, now):
        out.append(("stock", "", STOCK_SLOT))
    return out


def temp_status(key: str, value: float) -> str:
    """'ok' | 'bad' — уложилась ли камера в норму."""
    kind = next((c["kind"] for c in CAMERAS if c["key"] == key), "ch")
    n = NORMS[kind]
    return "ok" if n["lo"] <= value <= n["hi"] else "bad"


def temp_alarms(values: Dict[str, float]) -> List[Dict[str, Any]]:
    """Камеры вне нормы — то, ради чего замер вообще делается."""
    out = []
    for c in CAMERAS:
        v = values.get(c["key"])
        if v is None:
            continue
        if temp_status(c["key"], float(v)) == "bad":
            out.append({"key": c["key"], "title": c["title"], "value": float(v),
                        "norm": NORMS[c["kind"]]["txt"]})
    return out


def parse_temps(text: str) -> Tuple[Dict[str, float], Optional[str]]:
    """Разбирает ответ управляющего в числа по камерам.

    Принимаем как список из 9 чисел подряд («-20 4 -19 3 5 4 3 6 -21»), так и
    построчно. Минус набирают и дефисом, и типографским тире — приводим к одному.
    Возвращает (значения, ошибка).
    """
    norm = (text or "").replace("−", "-").replace("–", "-").replace(",", ".")
    tokens: List[float] = []
    for raw in norm.replace("\n", " ").split():
        t = raw.strip().rstrip("°cCсС").strip()
        if not t:
            continue
        try:
            tokens.append(float(t))
        except ValueError:
            return {}, f"«{raw}» — это не число. Пришлите {len(CAMERAS)} чисел по порядку."
    if len(tokens) != len(CAMERAS):
        return {}, (f"Нужно {len(CAMERAS)} чисел по порядку камер, "
                    f"а пришло {len(tokens)}.")
    for v in tokens:
        if not -60 <= v <= 40:
            return {}, f"{v} °C — похоже на опечатку. Проверьте показания."
    return {c["key"]: tokens[i] for i, c in enumerate(CAMERAS)}, None


def clean_task_text(zone: str, slot: str) -> str:
    """Текст задания по зоне — уходит управляющему в напоминание."""
    z = ZONES[zone]
    shots = "\n".join(f"   {i}. {s}" for i, s in enumerate(z["shots"], 1))
    return (f"{z['emoji']} <b>{z['title']}</b> · слот {slot} ({SLOT_LABEL.get(slot, '')})\n\n"
            f"Пришлите {len(z['shots'])} кадра:\n{shots}\n\n"
            f"<i>{CLEAN_PRINCIPLES}</i>")


def temp_task_text(slot: str) -> str:
    """Задание на замер температуры — список камер с нормой."""
    lines = [f"   {i}. {c['title']} — {NORMS[c['kind']]['txt']}"
             for i, c in enumerate(CAMERAS, 1)]
    return ("🌡 <b>Температура камер</b> · замер " + slot + "\n\n"
            + "\n".join(lines)
            + "\n\nОтветьте одним сообщением — "
              f"{len(CAMERAS)} чисел по порядку, через пробел.\n"
              "Например: <code>-20 4 -19 3 5 4 3 6 -21</code>")


def penalty_for(missing: int) -> int:
    """Штрафной балл за каждую несданную позицию. Просто и предсказуемо —
    сложная формула всё равно никого не убедит."""
    return max(0, int(missing))
